import streamlit as st
import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt

from sklearn.linear_model import LinearRegression
from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error, r2_score

st.set_page_config(page_title="Temperature Predictor", layout="centered")
st.title("🌡️ Temperature Prediction from Humidity")

uploaded_file = st.file_uploader("Upload humidity.csv file", type="csv")

if uploaded_file is not None:
    data = pd.read_csv(uploaded_file)
    data.columns = [col.strip().lower() for col in data.columns]

    if 'humidity' not in data.columns or 'temperature' not in data.columns:
        st.error("CSV must contain 'humidity' and 'temperature' columns.")
    else:
        st.subheader("Dataset Preview")
        st.dataframe(data.head())

        data = data.dropna()

        st.subheader("Exploratory Data Analysis")
        fig, ax = plt.subplots()
        sns.scatterplot(x=data['humidity'], y=data['temperature'], ax=ax)
        ax.set_title("Humidity vs Temperature")
        st.pyplot(fig)

        X = data[['humidity']]
        y = data['temperature']
        X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=0)

        model = LinearRegression()
        model.fit(X_train, y_train)

        y_pred = model.predict(X_test)
        mse = mean_squared_error(y_test, y_pred)
        r2 = r2_score(y_test, y_pred)

        st.subheader("Model Performance")
        st.write(f"📉 MSE: **{mse:.2f}**")
        st.write(f"📈 R² Score: **{r2:.2f}**")

        st.subheader("Make a Prediction")
        humidity_input = st.slider("Select Humidity (%)", float(X['humidity'].min()), float(X['humidity'].max()), 50.0)
        predicted_temp = model.predict(np.array([[humidity_input]]))[0]
        st.write(f"🌤️ Predicted Temperature: **{predicted_temp:.2f} °C**")